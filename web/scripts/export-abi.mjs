// Copies the contract's ABI from the Foundry build, so the site can't drift from the contract.
// The result is committed: hosts like Vercel build the site without Foundry and use that copy.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const source = new URL("../../contracts/out/SqueekMarkets.sol/SqueekMarkets.json", import.meta.url);
const target = new URL("../src/lib/abi.generated.ts", import.meta.url);
if (existsSync(source)) {
  const { abi } = JSON.parse(readFileSync(source));
  writeFileSync(target, `// Generated by scripts/export-abi.mjs. Don't edit by hand.\nexport const marketsAbi = ${JSON.stringify(abi)} as const;\n`);
} else if (!existsSync(target)) {
  console.error("No ABI: run `forge build` in contracts/ first.");
  process.exit(1);
}
